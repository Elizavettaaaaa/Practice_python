# Задача 2. Возраст и билет в кино

age = int(input("Введите возраст: "))

if age < 0 or age > 120:
    print("Ошибка: возраст должен быть от 0 до 120")
elif age < 6:
    print("Бесплатно")
elif age <= 17:
    print("Детский билет: 300 руб.")
elif age <= 64:
    print("Взрослый билет: 500 руб.")
else:
    print("Льготный билет: 250 руб.")